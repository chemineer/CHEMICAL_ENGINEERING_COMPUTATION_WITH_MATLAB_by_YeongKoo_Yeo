import numpy as np
from dfpopt import dfpopt

# 1. 목적 함수(fun) 정의
# 매트랩: fun = @(x) 100*(x(2)-x(1)^2)^2+(1-x(1))^2+90*(x(4)-x(3)^2)^2+(1-x(3))^2+10.1*((x(2)-1)^2+(x(4)-1)^2)+19.8*(x(2)-1)*(x(4)-1);
def fun(x):
    term1 = 100 * (x[1] - x[0]**2)**2 + (1 - x[0])**2
    term2 = 90 * (x[3] - x[2]**2)**2 + (1 - x[2])**2
    term3 = 10.1 * ((x[1] - 1)**2 + (x[3] - 1)**2)
    term4 = 19.8 * (x[1] - 1) * (x[3] - 1)
    return term1 + term2 + term3 + term4

# 2. 그레디언트 함수(delfun) 정의
# 매트랩: delfun = @(x) [400*x(1)*(x(1)^2-x(2))+2*(x(1)-1); 200*(x(2)-x(1)^2)+20.2*(x(2)-1)+19.8*(x(4)-1); 360*x(3)*(x(3)^2-x(4))+2*(x(3)-1); 180*(x(4)-x(3)^2)+20.2*(x(4)-1)+19.8*(x(2)-1)];
def delfun(x):
    g1 = 400 * x[0] * (x[0]**2 - x[1]) + 2 * (x[0] - 1)
    g2 = 200 * (x[1] - x[0]**2) + 20.2 * (x[1] - 1) + 19.8 * (x[3] - 1)
    g3 = 360 * x[2] * (x[2]**2 - x[3]) + 2 * (x[2] - 1)
    g4 = 180 * (x[3] - x[2]**2) + 20.2 * (x[3] - 1) + 19.8 * (x[1] - 1)
    return np.array([g1, g2, g3, g4])

# 3. 매개변수 설정
x0 = [-3.0, -1.0, -3.0, -1.0]  # 시작점
crit = 1e-6                    # 허용 오차
alpha0 = 2.0                   # 초기 스텝 사이즈
kmax = 1000                    # 최대 반복 횟수 (1e3)

# 4. DFP 최적화 함수 호출
# xopt: 최적점, fopt: 최솟값, iters: 반복 횟수
xopt, fopt, iters = dfpopt(fun, delfun, x0, alpha0, crit, kmax)

# 5. 결과 출력
print("--- DFP (Quasi-Newton) 최적화 결과 ---")
print(f"최적점 (xopt): {xopt}")
print(f"최솟값 (fopt): {fopt:.10f}")
print(f"반복 횟수 (iter): {iters}")