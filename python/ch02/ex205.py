import numpy as np

# 1. 계수 행렬 A 정의 (9x9 행렬)
# 각 행은 특정 격자점에서의 열 평형 방정식을 나타냅니다.
A = np.array([
    [-4,  2,  0,  0,  0,  2,  0,  0,  0],
    [ 1, -4,  1,  0,  0,  0,  1,  0,  0],
    [ 0,  1, -4,  1,  0,  0,  0,  1,  0],
    [ 0,  0,  2, -4,  0,  0,  0,  0,  1],
    [ 0,  0,  0,  0, -4,  2,  0,  0,  0],
    [ 1,  0,  0,  0,  1, -4,  1,  0,  0],
    [ 0,  1,  0,  0,  0,  1, -4,  1,  0],
    [ 0,  0,  1,  0,  0,  0,  1, -4,  1],
    [ 0,  0,  1,  0,  0,  0,  0,  2, -4]
], dtype=float)

# 2. 상수 벡터 b 정의 (경계 조건 및 열원 반영)
b = np.array([0, -500, -500, -500, -400, -200, -200, -200, -200], dtype=float)

# 3. 선형 방정식 해 구하기 (MATLAB의 x = A\b와 동일)
# 내부적으로 LU 분해 등을 사용하여 효율적으로 계산합니다.
x = np.linalg.solve(A, b)

# 4. 결과 출력
print("Temperature distribution (x):")
# 가독성을 위해 3x3 격자 형태로 출력 (필요 시)
print(x.reshape(3, 3))

# 상세 값 출력
for i, temp in enumerate(x):
    print(f"Node {i+1}: {temp:.2f}")