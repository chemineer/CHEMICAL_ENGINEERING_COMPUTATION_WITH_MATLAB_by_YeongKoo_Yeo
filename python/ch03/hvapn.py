import numpy as np
from compID import compID

def hvapn(T, cname):
    """
    Estimation of heat of vaporization (cal/g)
    T: temperature(C) (scalar or array)
    cname: common name or chemical formula of the compound
    """
    
    # 파라미터 행렬 (dhv1, T1(C), Tc(C), r)
    cv = np.array([
        [41.1000, -188.1000, -129.000, 0.3800], [69.6000, -34.0600, 144.0000, 0.3800],
        [93.0000, -10.0000, 157.6000, 0.3800], [51.6000, -191.5000, -140.1000, 0.3800],
        [56.1000, 0, 31.1000, 0.3800], [105.8000, -85.0300, 51.5000, 0.3800],
        [327.4000, -33.4300, 132.4000, 0.3800], [538.7000, 100.0000, 374.2000, 0.3800],
        [321.9000, 150.2000, 455.0000, 0.3800], [107.0000, -252.8000, -240.2000, 0.2370],
        [47.5000, -195.8000, -146.8000, 0.3800], [50.9000, -183.0000, -118.5000, 0.3800],
        [115.4000, -103.7000, 9.9000, 0.3800], [121.7000, -161.5000, -82.6000, 0.3800],
        [116.7000, -88.2000, 32.3000, 0.3800], [101.8000, -42.1000, 96.7000, 0.3800],
        [94.1000, 80.1000, 288.9400, 0.3800], [86.1000, 110.6000, 318.8000, 0.3800],
        [112.4000, 184.4000, 426.0000, 0.3800], [116.4000, 181.8000, 420.0000, 0.3800],
        [113.8000, -32.8000, 124.9000, 0.3800], [0.0, 0.0, 0.0, 0.0],  # missing component (C6H12)
        [100.2000, -4.4100, 152.0000, 0.3800], [260.1000, 64.7000, 239.4000, 0.4000],
        [58.9000, 61.3000, 263.4000, 0.3800], [46.5500, 76.7000, 283.2000, 0.3800]
    ])
    
    # compID 함수는 외부 정의가 필요합니다.
    ind = compID(cname)
    
    # 인덱스 보정 (MATLAB 1-based -> Python 0-based)
    idx = ind - 1
    
    # 온도 변환 (C -> K)
    T0 = 273.15
    T_k = np.array(T) + T0
    Tc = cv[idx, 2] + T0
    T1 = cv[idx, 1] + T0
    
    # 증발열 계산 (cal/g)
    # 수식: dhv1 * ((Tc - T) / (Tc - T1)) ^ r
    hv = cv[idx, 0] * ((Tc - T_k) / (Tc - T1)) ** cv[idx, 3]
    
    return hv