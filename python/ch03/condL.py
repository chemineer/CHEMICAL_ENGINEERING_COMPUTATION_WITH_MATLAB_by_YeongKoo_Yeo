import numpy as np
from compID import compID

def condL(T, cname):
    """
    액체의 열전도도(microcal/cm/sec/C)를 계산하는 함수
    """
    # 상관계수 행렬 cv (1000이 곱해진 상태)
    cv_raw = np.array([
        [0.6215, -0.1623, -0.1184], [0.5590, -0.0483, -0.0152],
        [2.1408, -0.7837, 0.0714], [0.4755, 0.0033, -0.2143],
        [0.9721, -0.2015, -0.0230], [1.0717, -0.0184, -0.0658],
        [2.5513, -0.3766, -0.0294], [-0.9166, 1.2547, -0.1521],
        [-0.4666, 0.8059, -0.0876], [-0.0201, 2.4737, -5.3473],
        [0.6280, -0.3689, -0.0226], [0.5838, -0.2105, -0.0483],
        [0.8515, -0.2289, -0.0047], [0.7227, -0.1444, -0.0764],
        [0.6993, -0.1659, -0.0049], [0.6235, -0.1268, -0.0021],
        [0.4243, 0.0011, -0.0090], [0.4851, -0.0538, -0.0006],
        [0.5375, -0.0304, -0.0015], [0.4409, 0.0867, -0.0070],
        [0.3968, -0.0421, -0.0067], [0.3883, -0.0227, -0.0033],
        [0.7183, -0.1872, 0.0117], [0.7701, -0.1142, 0.0028],
        [0.3902, -0.0206, -0.0051]
    ])
    cv = 1000 * cv_raw
    
    # 계수 조정 (wv 생성)
    # 각 열에 1, 1e-2, 1e-4를 곱함
    multipliers = np.array([1, 1e-2, 1e-4])
    wv = cv * multipliers
    
    # 화합물 ID 확인 (기존에 정의한 compID 함수 호출)
    ind = compID(cname)
    
    if ind is None:
        print("Error: 화합물 이름을 확인할 수 없습니다.")
        return None
    
    # MATLAB 인덱스 1은 파이썬 0에 해당
    if ind > len(wv):
        print("Error: 해당 화합물의 액체 데이터가 cv 행렬에 존재하지 않습니다.")
        return None

    w = wv[ind - 1]
    
    # T 계산 (스칼라 혹은 배열 대응)
    T = np.array(T)
    k = w[0] + w[1]*T + w[2]*(T**2)
    
    print(f' Thermal conductivity = {k} microcal/cm/sec/C')
    return k

