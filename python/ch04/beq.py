import numpy as np

def beq(t, z, P):
    """
    비선형 연립 방정식 시스템을 정의합니다.
    t: [x11, x21, x12, x22, T, beta] (변수 벡터)
    z: 입력 조성 벡터
    P: 압력
    """
    # t를 개별 변수로 할당 (0-기반 인덱싱)
    x11, x21, x12, x22, T, beta = t

    # 필요한 관계식 계산
    P1 = 10**(7.62231 - 1417.9 / (191.15 + T))
    P2 = 10**(8.10765 - 1750.29 / (235 + T))
    
    gam11 = 10**(1.7 * x21**2 / ((2.43 * x11 + x21)**2))
    gam12 = 10**(1.7 * x22**2 / ((2.43 * x12 + x22)**2))
    gam21 = 10**(0.7 * x11**2 / ((x11 + 0.412 * x21)**2))
    gam22 = 10**(0.7 * x12**2 / ((x12 + 0.412 * x22)**2))
    
    k11 = gam11 * P1 / P
    k12 = gam12 * P1 / P
    k21 = gam21 * P2 / P
    k22 = gam22 * P2 / P
    
    # 비선형 방정식 시스템 f(t) 정의
    f = np.zeros(6)
    
    f[0] = x11 - z[0] / (beta + (1 - beta) * k11 / k12) # i=1
    f[1] = x21 - z[1] / (beta + (1 - beta) * k21 / k22) # i=2
    f[2] = x12 - x11 * k11 / k12
    f[3] = x22 - x21 * k21 / k22
    f[4] = x11 + x21 - x12 - x22
    f[5] = x11 * (1 - k11) + x21 * (1 - k21)
    
    return f