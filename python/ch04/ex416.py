import numpy as np
from unifgam import unifgam

# 1. 데이터 정의
Nc = 4  # 성분의 수
k = 6   # 작용기의 수

# R: 각 작용기의 부피 벡터
R = np.array([0.9011, 0.6744, 0.4469, 0.2195, 0.5313, 1.0000])

# Q: 각 작용기의 표면적 벡터
Q = np.array([0.848, 0.540, 0.228, 0.000, 0.400, 1.200])

# nu: 작용기의 수 (6x4 행렬)
nu = np.array([
    [2, 1, 3, 0],
    [4, 1, 1, 0],
    [0, 0, 1, 0],
    [0, 0, 1, 0],
    [0, 0, 0, 6],
    [0, 1, 0, 0]
])

# amn: 그룹 상호작용 매개변수 행렬 (6x6)
amn = np.array([
    [0, 0, 0, 0, 61.13, 986.5],
    [0, 0, 0, 0, 61.13, 986.5],
    [0, 0, 0, 0, 61.13, 986.5],
    [0, 0, 0, 0, 61.13, 986.5],
    [-11.12, -11.12, -11.12, -11.12, 0, 636.1],
    [156.4, 156.4, 156.4, 156.4, 89.60, 0]
])

T = 334.82                # 온도 (K)
x = np.array([0.162, 0.068, 0.656, 0.114])  # 몰 분율

# 2. 활동도 계수 계산
gam = unifgam(k, R, Q, nu, amn, Nc, x, T)

# 3. 결과 출력
print(f"--- UNIFAC 계산 결과 (T = {T} K) ---")
for i, g in enumerate(gam):
    print(f"성분 {i+1}의 활동도 계수 (gamma[{i+1}]): {g:.4f}")